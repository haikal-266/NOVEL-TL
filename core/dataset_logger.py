"""
Novel TL - Parallel Dataset Logger
Passively records high-quality (JA, ID, EN) translation pairs generated by Gemini Flash
to disk (data/gemini_dataset.jsonl) for future offline VelTL model training and fine-tuning.
"""

import os
import json
import hashlib
import threading
import datetime
from typing import Dict, List, Any, Optional

DATA_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "data"))
DATASET_FILE = os.path.join(DATA_DIR, "gemini_dataset.jsonl")

class DatasetLogger:
    _instance = None
    _lock = threading.Lock()

    def __new__(cls):
        with cls._lock:
            if cls._instance is None:
                cls._instance = super(DatasetLogger, cls).__new__(cls)
                cls._instance._init_logger()
            return cls._instance

    def _init_logger(self) -> None:
        self.file_path = DATASET_FILE
        self.write_lock = threading.Lock()
        self.seen_hashes = set()
        os.makedirs(DATA_DIR, exist_ok=True)
        self._load_existing_hashes()

    def _load_existing_hashes(self) -> None:
        """Loads hashes of already logged entries to prevent duplicates."""
        if not os.path.exists(self.file_path):
            return
        try:
            with open(self.file_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        data = json.loads(line)
                        h = data.get("hash") or self._make_hash(data.get("ja", ""), data.get("id", ""))
                        self.seen_hashes.add(h)
                    except Exception:
                        continue
        except Exception as e:
            print(f"[DatasetLogger] Warning reading existing hashes: {e}")

    @staticmethod
    def _make_hash(ja: str, id_text: str) -> str:
        raw = f"{ja.strip()}|||{id_text.strip()}"
        return hashlib.md5(raw.encode("utf-8")).hexdigest()

    def log_pair(
        self,
        ja: str,
        id_text: str,
        en_text: str = "",
        work_id: str = "",
        chapter_id: str = "",
        chapter_index: int = 0,
        p_index: int = 0,
        model: str = "gemini-flash"
    ) -> bool:
        """Logs a single translation pair. Returns True if newly added, False if duplicate or empty."""
        ja_clean = (ja or "").strip()
        id_clean = (id_text or "").strip()
        if not ja_clean or not id_clean:
            return False

        entry_hash = self._make_hash(ja_clean, id_clean)
        with self.write_lock:
            if entry_hash in self.seen_hashes:
                return False

            now = datetime.datetime.now(datetime.timezone.utc).isoformat()
            record = {
                "hash": entry_hash,
                "timestamp": now,
                "work_id": work_id,
                "chapter_id": chapter_id,
                "chapter_index": chapter_index,
                "p_index": p_index,
                "ja": ja_clean,
                "en": (en_text or "").strip(),
                "id": id_clean,
                "model": model
            }

            try:
                with open(self.file_path, "a", encoding="utf-8") as f:
                    f.write(json.dumps(record, ensure_ascii=False) + "\n")
                self.seen_hashes.add(entry_hash)
                return True
            except Exception as e:
                print(f"[DatasetLogger] Failed to write entry: {e}")
                return False

    def log_pairs(self, pairs: List[Dict[str, Any]]) -> int:
        """Batch logs a list of translation pairs. Returns count of newly saved pairs."""
        added = 0
        for p in pairs:
            if self.log_pair(
                ja=p.get("ja", ""),
                id_text=p.get("id", ""),
                en_text=p.get("en", ""),
                work_id=p.get("work_id", ""),
                chapter_id=p.get("chapter_id", ""),
                chapter_index=p.get("chapter_index", 0),
                p_index=p.get("p_index", 0),
                model=p.get("model", "gemini-flash")
            ):
                added += 1
        return added

    def get_stats(self) -> Dict[str, Any]:
        """Returns statistical overview of the accumulated dataset."""
        total_pairs = len(self.seen_hashes)
        file_size_kb = 0.0
        unique_novels = set()
        unique_chapters = set()
        recent_samples = []

        if os.path.exists(self.file_path):
            file_size_kb = round(os.path.getsize(self.file_path) / 1024.0, 2)
            try:
                with open(self.file_path, "r", encoding="utf-8") as f:
                    lines = f.readlines()
                    total_pairs = len(lines)
                    for l in lines[-10:]:
                        l = l.strip()
                        if not l:
                            continue
                        try:
                            d = json.loads(l)
                            if d.get("work_id"):
                                unique_novels.add(d["work_id"])
                            if d.get("chapter_id"):
                                unique_chapters.add(d["chapter_id"])
                            recent_samples.append({
                                "ja": d.get("ja", "")[:70],
                                "id": d.get("id", "")[:70],
                                "work_id": d.get("work_id", "")
                            })
                        except Exception:
                            pass
            except Exception as e:
                print(f"[DatasetLogger] Error getting stats: {e}")

        return {
            "total_pairs": total_pairs,
            "unique_novels": len(unique_novels),
            "unique_chapters": len(unique_chapters),
            "file_size_kb": file_size_kb,
            "dataset_file": self.file_path,
            "recent_samples": recent_samples[-5:]
        }

_logger_instance = None

def get_dataset_logger() -> DatasetLogger:
    global _logger_instance
    if _logger_instance is None:
        _logger_instance = DatasetLogger()
    return _logger_instance
